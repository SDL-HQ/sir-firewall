ROOT = Path(__file__).resolve().parents[1]


def _load_tool(name: str):
    path = ROOT / "tools" / f"{name}.py"
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_certificate_generator_uses_package_version():
    generator = _load_tool("generate_certificate")

    assert generator._sir_firewall_version() == sir_firewall.__version__


def test_local_audit_uses_package_version():
    local_audit = _load_tool("local_audit")

    assert local_audit._sir_version() == sir_firewall.__version__


def test_current_state_statements_match_runtime_authority():
    """Derive the expected version for narrowly defined current-state claims."""

    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    perimeter = (ROOT / "docs/evidence-perimeter.v6.md").read_text(encoding="utf-8")
    failure_modes = (ROOT / "docs/failure-modes.md").read_text(encoding="utf-8")
    rule_coverage = (ROOT / "docs/rule-coverage.md").read_text(encoding="utf-8")

    current_implementation = perimeter.split(
        "## Current implementation state\n", 1
    )[1].split("\n## ", 1)[0]
    current_versions = {
        "README title": re.search(
            r"\A# SIR: Signal Integrity Resolver Version (\d+\.\d+\.\d+)$",
            readme,
            flags=re.MULTILINE,
        ),
        "evidence perimeter current implementation state": re.search(
            r"The code reports SIR version `(\d+\.\d+\.\d+)` in package metadata "
            r"and `sir_firewall\.__version__`\.",
            current_implementation,
        ),
        "failure modes opening statement": re.search(
            r"^This note describes SIR (\d+\.\d+\.\d+) as implemented,",
            failure_modes,
            flags=re.MULTILINE,
        ),
        "failure modes current behaviour heading": re.search(
            r"^## Current (\d+\.\d+\.\d+) behaviour$",
            failure_modes,
            flags=re.MULTILINE,
        ),
        "rule coverage generation statement": re.search(
            r"^`spec/packs/pack_registry\.v1\.json` at SIR (\d+\.\d+\.\d+)\. "
            r"It is generated by a$",
            rule_coverage,
            flags=re.MULTILINE,
        ),
    }

    assert all(current_versions.values()), current_versions
    assert {name: match.group(1) for name, match in current_versions.items()} == {
        name: sir_firewall.__version__ for name in current_versions
    }


